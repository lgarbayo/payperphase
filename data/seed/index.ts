/**
 * OWNED BY WP-02. Seed cases used by the store's seed-on-boot and demo reset (WP-09).
 * SCAFFOLD STUB: only the golden implant case and its sample entry (no PDF yet, empty sha256); WP-02 adds
 * the aligner case (and optional perio case), generates the PDFs under public/samples/ and fills sha256.
 * Keep the exported names: WP-03 (extraction fallback), WP-07 (samples) and WP-09 (seed) import them.
 */
import type { CaseKind, ExtractionResult } from "@/contracts";
import { GOLDEN_EXTRACTION, GOLDEN_PLAN } from "@/contracts/fixtures/implantCase";
import type { Plan } from "@/contracts";

export interface SeedCase {
  key: string;
  caseKind: CaseKind;
  /** The hero case is the one Director Mode and the alias "demo" use. */
  hero: boolean;
  extraction: ExtractionResult;
  /** Approved plan as seeded (dates relative to SIM_DEFAULT_START). */
  plan: Plan;
  /** Path under /public of the synthetic PDF, served for download/drag in the clinic console. */
  samplePdf: string | null;
}

export function seedCases(): SeedCase[] {
  return [
    {
      key: "implant-ribera",
      caseKind: "implant",
      hero: true,
      extraction: structuredClone(GOLDEN_EXTRACTION),
      plan: structuredClone(GOLDEN_PLAN),
      samplePdf: null,
    },
  ];
}

/** Samples offered in the clinic dropzone ("Try a sample"). The id equals the SeedCase key. */
export interface SamplePdf {
  id: string;
  caseKind: CaseKind;
  label: { es: string; en: string };
  /** URL path under /public (the file itself is generated by WP-02's `npm run pdfs`). */
  path: string;
  /** Hex sha256 of the committed PDF bytes; keys WP-03's cached fallback. Empty until WP-02 generates it. */
  sha256: string;
}
export const SAMPLE_PDFS: SamplePdf[] = [
  {
    id: "implant-ribera",
    caseKind: "implant",
    label: { es: "Implantes · Clínica Dental Ribera (ficticio)", en: "Implants · Clínica Dental Ribera (synthetic)" },
    path: "/samples/presupuesto-implantes-ribera.pdf",
    sha256: "",
  },
];

/** Golden extraction for a sample id (WP-03 `{sampleId}` path and cached fallback), or null. */
export function cachedExtractionBySampleId(sampleId: string): ExtractionResult | null {
  const c = seedCases().find((x) => x.key === sampleId);
  return c ? structuredClone(c.extraction) : null;
}

/** Golden extraction for a known sample PDF by its sha256 (WP-03 cached fallback), or null. */
export function cachedExtractionBySha(sha256: string): ExtractionResult | null {
  const sample = SAMPLE_PDFS.find((s) => s.sha256 !== "" && s.sha256 === sha256);
  return sample ? cachedExtractionBySampleId(sample.id) : null;
}
